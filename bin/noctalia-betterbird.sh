#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
exec </dev/null
# noctalia-betterbird.sh
# Noctalia pipeline module — Betterbird folder icon recolouring + spaces bar
# ─────────────────────────────────────────────────────────────────────────────

set -euo pipefail

COLORS_FILE="$HOME/.config/noctalia/colors.json"
ICON_THEME_DIR="$HOME/.local/share/icons/Tela-Noctalia-Active"
OUTPUT_DIR="$HOME/.config/betterbird/noctalia-icons"

TELA_PLACES="$ICON_THEME_DIR/scalable/places"
TELA_ACTIONS="$ICON_THEME_DIR/scalable/actions"
TELA_STATUS="$ICON_THEME_DIR/scalable/status"
ADWAITA="/usr/share/icons/Adwaita/symbolic"

# ── Read colours from colors.json ───────────────────────────────────────────
if [[ ! -f "$COLORS_FILE" ]]; then
    echo "noctalia-betterbird: colors.json not found at $COLORS_FILE" >&2
    exit 1
fi

sleep 0.5
unset PRIMARY
unset SURFACE
PRIMARY=$(python3 -c "
import json
data = json.load(open('$COLORS_FILE'))
print(data.get('mPrimary', data.get('primary', '#7c9cbf')))
")


SURFACE_VARIANT=$(python3 -c "
import json
data = json.load(open('$COLORS_FILE'))
print(data.get('mSurfaceVariant', data.get('surfaceVariant', '#1f1f28')))
")
SURFACE_VARIANT="${SURFACE_VARIANT:-#1f1f28}"

SURFACE=$(python3 -c "
import json
data = json.load(open('$COLORS_FILE'))
print(data.get('mSurface', data.get('surface', '#1f1f28')))
")
SURFACE="${SURFACE:-#1f1f28}"

echo "noctalia-betterbird: primary=$PRIMARY surface=$SURFACE"

mkdir -p "$OUTPUT_DIR"

# ── Icon mapping ─────────────────────────────────────────────────────────────
declare -A ICON_MAP=(
    ["folder"]="$ADWAITA/places/folder-symbolic.svg"
    ["inbox"]="$ADWAITA/status/mail-unread-symbolic.svg"
    ["sent"]="$ADWAITA/actions/mail-send-symbolic.svg"
    ["drafts"]="$ADWAITA/actions/document-edit-symbolic.svg"
    ["archive"]="$ADWAITA/status/mail-unread-symbolic.svg"
    ["trash"]="$ADWAITA/places/user-trash-symbolic.svg"
    ["spam"]="$ADWAITA/actions/mail-mark-junk-symbolic.svg"
    ["outbox"]="$ADWAITA/actions/mail-forward-symbolic.svg"
    ["templates"]="$ADWAITA/actions/document-edit-symbolic.svg"
    ["starred"]="$ADWAITA/actions/star-new-symbolic.svg"
    ["account"]="$ADWAITA/legacy/system-users-symbolic.svg"
)

FALLBACK_TRASH=(
    "$TELA_STATUS/user-trash-full.svg"
    "$TELA_ACTIONS/edit-delete-symbolic.svg"
    "$TELA_PLACES/folder.svg"
)
FALLBACK_STARRED=(
    "$TELA_ACTIONS/starred.svg"
    "$TELA_STATUS/starred.svg"
    "$TELA_PLACES/folder.svg"
)
FALLBACK_SPAM=(
    "$TELA_STATUS/dialog-warning-symbolic.svg"
    "$TELA_PLACES/folder.svg"
)

recolour_svg() {
    local src="$1" dest="$2" colour="$3"
    [[ ! -f "$src" ]] && echo "noctalia-betterbird: WARNING source SVG not found: $src" >&2 && return 1
    cp "$src" "$dest"
    sed -i \
        -e "s/fill=\"currentColor\"/fill=\"$colour\"/g" \
        -e "s/fill:currentColor/fill:$colour/g" \
        -e "s/stroke=\"currentColor\"/stroke=\"$colour\"/g" \
        -e "s/\.ColorScheme-Text\s*{[^}]*color:[^}]*}/\.ColorScheme-Text{color:$colour}/g" \
        -e "s/fill=\"#[0-9a-fA-F]\{6\}\"/fill=\"$colour\"/g" \
        "$dest"
}

resolve_src() {
    local name="$1"
    local src="${ICON_MAP[$name]}"
    [[ -f "$src" ]] && echo "$src" && return
    echo "$ADWAITA/places/folder-symbolic.svg"
}

# ── Recolour folder icons ────────────────────────────────────────────────────
for icon_name in "${!ICON_MAP[@]}"; do
    src=$(resolve_src "$icon_name")
    dest="$OUTPUT_DIR/${icon_name}.svg"
    if recolour_svg "$src" "$dest" "$PRIMARY"; then
        echo "noctalia-betterbird:   ✓ ${icon_name}.svg"
    else
        echo "noctalia-betterbird:   ✗ ${icon_name}.svg (source missing, skipped)"
    fi
done

# Write dynamic colour CSS
# This file is @imported by userChrome.css and contains only the colour
# variables that change with each Noctalia palette switch.
cat > "$OUTPUT_DIR/noctalia-colors.css" << EOF
/* Auto-generated by noctalia-betterbird.sh - do not edit manually */
:root {
  /* Spaces toolbar: recolour icons to Noctalia primary */
  --spaces-button-text-color: $PRIMARY !important;
  /* Unread folder text colour */
  --folder-pane-unread-color: $PRIMARY !important;
  /* Message card and tree view background */
  --tree-card-background: $SURFACE_VARIANT !important;
  --tree-view-bg: $SURFACE_VARIANT !important;
  --layout-background-0: $SURFACE_VARIANT !important;
  --tree-pane-background: $SURFACE !important;

  /* Message list pane background */
  --thread-pane-background: $SURFACE_VARIANT !important;
  --listbox-background: $SURFACE_VARIANT !important;

  /* Folder pane background to match Noctalia surface */
  --folderpane-background: $SURFACE !important;
  --color-blue-30: $PRIMARY !important;
  --color-blue-40: $PRIMARY !important;
  --color-blue-50: $PRIMARY !important;
  --color-blue-60: $PRIMARY !important;
  --color-blue-70: $PRIMARY !important;
  --color-accent-primary: $PRIMARY !important;
  --color-accent-primary-hover: $PRIMARY !important;
  --color-accent-primary-active: $PRIMARY !important;
  --link-color: $PRIMARY !important;
  --link-color-hover: $PRIMARY !important;
  --link-color-visited: $PRIMARY !important;
}
EOF
echo "noctalia-betterbird:   ✓ noctalia-colors.css"
echo "noctalia-betterbird: done → $OUTPUT_DIR"

# ── Write tray icons ─────────────────────────────────────────────────────────
ERROR=$(python3 -c "
import json
data = json.load(open('$HOME/.config/noctalia/colors.json'))
print(data.get('mError', data.get('error', '#e46876')))
")
ERROR="${ERROR:-#e46876}"

cat > "$OUTPUT_DIR/default.svg" << SVGEOF
<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="1000" viewBox="0 0 1000 1000">
  <rect x="80" y="220" width="840" height="560" rx="60" ry="60"
        fill="none" stroke="$PRIMARY" stroke-width="70"/>
  <polyline points="80,220 500,580 920,220"
            fill="none" stroke="$PRIMARY" stroke-width="70"
            stroke-linejoin="round" stroke-linecap="round"/>
</svg>
SVGEOF
echo "noctalia-betterbird:   ✓ default.svg (tray normal)"

cat > "$OUTPUT_DIR/newmail.svg" << SVGEOF
<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="1000" viewBox="0 0 1000 1000">
  <rect x="80" y="220" width="840" height="560" rx="60" ry="60"
        fill="none" stroke="$PRIMARY" stroke-width="70"/>
  <polyline points="80,220 500,580 920,220"
            fill="none" stroke="$PRIMARY" stroke-width="70"
            stroke-linejoin="round" stroke-linecap="round"/>
  <circle cx="820" cy="220" r="140" fill="$ERROR"/>
</svg>
SVGEOF
echo "noctalia-betterbird:   ✓ newmail.svg (tray new mail)"

sudo cp "$OUTPUT_DIR/default.svg" /opt/betterbird/chrome/icons/default/default.svg
sudo cp "$OUTPUT_DIR/newmail.svg" /opt/betterbird/chrome/icons/default/newmail.svg
echo "noctalia-betterbird:   ✓ tray icons installed to /opt/betterbird"
